#!/usr/bin/env python3
"""Fail when mypy errors per module rise above ``mypy-baseline.txt``.

A module missing from the baseline is treated as zero. A new module with a
count above zero fails. Lowering a count requires updating the baseline in
the same commit (``python3 scripts/mypy_ratchet.py --write``).

``strict_modules`` is the per-module promotion list. It is empty until a
later change opts a zero-baseline module into ``mypy --strict``.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from collections import Counter
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
BASELINE_PATH = REPO_ROOT / "mypy-baseline.txt"
TARGETS = ["contracts", "src/recertia"]

# Modules already at zero that a later PR promotes to --strict.
strict_modules: list[str] = []

_ERROR_RE = re.compile(r"^(.+?):(\d+): error:")


def parse_mypy_output(text: str) -> Counter[str]:
    counts: Counter[str] = Counter()
    for line in text.splitlines():
        match = _ERROR_RE.match(line)
        if match:
            counts[match.group(1)] += 1
    return counts


def read_baseline(path: Path) -> dict[str, int]:
    if not path.exists():
        return {}
    counts: dict[str, int] = {}
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        module, _, count = line.rpartition(" ")
        counts[module] = int(count)
    return counts


def render_baseline(counts: Counter[str]) -> str:
    lines = [
        "# module error-count. Generated by scripts/mypy_ratchet.py --write.",
        "# Counts may only shrink. A missing module means zero.",
        "",
    ]
    for module in sorted(counts):
        if counts[module] > 0:
            lines.append(f"{module} {counts[module]}")
    lines.append("")
    return "\n".join(lines)


def compare_counts(actual: Counter[str], baseline: dict[str, int]) -> list[str]:
    """Return human-readable failures. Empty means the ratchet holds."""

    failures: list[str] = []
    modules = set(actual) | set(baseline)
    for module in sorted(modules):
        now = actual.get(module, 0)
        was = baseline.get(module, 0)
        if now > was:
            if was == 0 and module not in baseline:
                failures.append(f"{module}: new module with {now} mypy error(s)")
            else:
                failures.append(f"{module}: {was} -> {now} mypy errors")
    return failures


def run_mypy() -> Counter[str]:
    cmd = [sys.executable, "-m", "mypy", "--no-error-summary", *TARGETS]
    for module in strict_modules:
        cmd.extend(["--strict", module])  # pragma: no cover — list starts empty
    proc = subprocess.run(cmd, cwd=REPO_ROOT, capture_output=True, text=True)
    # mypy exits 1 when it finds errors. That is an input to the ratchet, not a crash.
    if proc.returncode not in {0, 1}:
        sys.stderr.write(proc.stderr or proc.stdout)
        raise SystemExit(proc.returncode)
    return parse_mypy_output(proc.stdout)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="rewrite mypy-baseline.txt")
    args = parser.parse_args(argv)
    actual = run_mypy()
    if args.write:
        BASELINE_PATH.write_text(render_baseline(actual), encoding="utf-8")
        print(f"wrote {BASELINE_PATH}")
        return 0
    failures = compare_counts(actual, read_baseline(BASELINE_PATH))
    if failures:
        print("mypy ratchet failed:", file=sys.stderr)
        for line in failures:
            print(f"  {line}", file=sys.stderr)
        return 1
    print(f"mypy ratchet ok ({sum(actual.values())} errors, baseline holds)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
